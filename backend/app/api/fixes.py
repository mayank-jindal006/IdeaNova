from __future__ import annotations

from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy.orm import Session

from app.db.models import Finding, FindingStatus, Fix, FixStatus, Repo, User
from app.auth import current_user
from app.db.session import get_db
from app.github_client.client import commit_file_changes, create_branch, open_pull_request
from app.schemas import OpenPrOut

router = APIRouter(prefix="/fixes", tags=["fixes"])


@router.post("/{fix_id}/open-pr", response_model=OpenPrOut)
def open_pr(fix_id: int, db: Session = Depends(get_db), user: User = Depends(current_user)) -> OpenPrOut:
    fix = db.scalar(__import__('sqlalchemy').select(Fix).join(Finding).join(Repo).where(Fix.id == fix_id, Repo.owner_id == user.id))
    if not fix:
        raise HTTPException(404, "Fix not found")
    finding = db.get(Finding, fix.finding_id)
    repo = db.get(Repo, finding.repo_id) if finding else None
    if not finding or not repo:
        raise HTTPException(404, "Finding or repository not found")
    branch = f"repoguard/fix-{finding.id}"
    create_branch(repo.full_name, branch, repo.default_branch)
    commit_file_changes(repo.full_name, branch, fix.edits)
    explanation = fix.explanation
    body = (
        f"## 🔐 RepoGuard: {finding.title}\n**Severity:** {finding.severity.value if finding.severity else 'unknown'} · **Rule:** {finding.rule_id} · **OWASP:** {finding.owasp_ids} · **ASVS:** {finding.asvs_ids}\n\n"
        f"### What was found\n{explanation['what']}\n\n### Why it's dangerous\n{explanation['why_dangerous']}\n\n"
        f"### What this PR changes\n{explanation['how_fixed']}\n\n### ⚠️ Rotation required\n{explanation['rotation_note']}\n"
        "This PR removes the secret from the current code, but it remains in git history.\n"
        "Revoke and rotate the credential before merging.\n\n_Generated by RepoGuard. Review before merging. Nothing is merged automatically._"
    )
    pr_url, pr_number = open_pull_request(repo.full_name, branch, repo.default_branch, f"RepoGuard: {finding.title}", body)
    fix.pr_url, fix.pr_number, fix.status, finding.status = pr_url, pr_number, FixStatus.pr_opened, FindingStatus.pr_opened
    db.commit()
    return OpenPrOut(pr_url=pr_url, pr_number=pr_number)
